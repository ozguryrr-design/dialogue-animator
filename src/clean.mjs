// `da clean <dir> [--all]`: delete temporary render files (build/tmp) or the whole build/ folder.
import path from 'node:path';
import fs from 'node:fs';
import { log, rel, dirSize, humanBytes, exists } from './lib/util.mjs';
import { scanProject } from './project/config.mjs';

export async function cli(args) {
  const files = scanProject(args._[0] || '.');
  const target = args.all ? files.build : path.join(files.build, 'tmp');
  if (!exists(target)) { log.ok(`nothing to clean (${rel(target)} does not exist)`); return 0; }
  const size = dirSize(target);
  fs.rmSync(target, { recursive: true, force: true });
  log.ok(`deleted ${rel(target)} (${humanBytes(size)})`);
  if (!args.all) log.info('use --all to delete the whole build/ folder (it is regenerated by `da make`)');
  return 0;
}
